class soc_test;

    //========================================================
    // VIRTUAL INTERFACE
    //========================================================

    virtual soc_if vif;


    //========================================================
    // ENVIRONMENT
    //========================================================

    soc_env env;


    //========================================================
    // CONSTRUCTOR
    //========================================================

    function new(
        virtual soc_if vif
    );

        this.vif = vif;

        env = new(vif);

    endfunction


    //========================================================
    // RUN
    //========================================================

    task run();

        $display("");
        $display("================================================");
        $display("          SOC VERIFICATION STARTED");
        $display("================================================");
        $display("");

        // Run complete verification environment
        env.run();

        $display("");
        $display("================================================");
        $display("          SOC VERIFICATION COMPLETED");
        $display("================================================");
        $display("");

    endtask

endclass
